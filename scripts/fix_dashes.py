#!/usr/bin/env python3
"""Fix corrupted em/en dashes in tools.json at byte level."""
path = 'data/tools.json'

with open(path, 'rb') as f:
    raw = f.read()

# The common corrupted sequence prefix (30 bytes)  
corrupted_en_dash = bytes([
    0xc3, 0x83, 0xc6, 0x92, 0xc3, 0x82, 0xc2, 0xa2,
    0xc3, 0x83, 0xc2, 0xa2, 0xc3, 0xa2, 0xe2, 0x82,
    0xac, 0xc5, 0xa1, 0xc3, 0x82, 0xc2, 0xac, 0xc3,
    0x83, 0xc2, 0xa2, 0xc3, 0xa2, 0xe2, 0x80, 0x9a,
    0xc2, 0xac, 0xc3, 0x85, 0xe2, 0x80, 0x9c
])  # 39 bytes - this is the corrupted en dash between 16-128

corrupted_em_dash = bytes([
    0xc3, 0x83, 0xc6, 0x92, 0xc3, 0x82, 0xc2, 0xa2,
    0xc3, 0x83, 0xc2, 0xa2, 0xc3, 0xa2, 0xe2, 0x82,
    0xac, 0xc5, 0xa1, 0xc3, 0x82, 0xc2, 0xac, 0xc3,
    0x83, 0xc2, 0xa2, 0xc3, 0xa2, 0xe2, 0x80, 0x9a,
    0xc2, 0xac, 0xc3, 0x82, 0xc2, 0x9d
])  # 38 bytes - this is the corrupted em dash

# Longer variant found in chrome-session-viewer
corrupted_em_dash_long = bytes([
    0xc3, 0x83, 0xc6, 0x92, 0xc3, 0x86, 0xe2, 0x80,
    0x99, 0xc3, 0x83, 0xe2, 0x80, 0x9a, 0xc3, 0x82,
    0xc2, 0xa2, 0xc3, 0x83, 0xc6, 0x92, 0xc3, 0x82,
    0xc2, 0xa2, 0xc3, 0x83, 0xc2, 0xa2, 0xc3, 0xa2,
    0xe2, 0x80, 0x9a, 0xc2, 0xac, 0xc3, 0x85, 0xc2,
    0xa1, 0xc3, 0x83, 0xe2, 0x80, 0x9a, 0xc3, 0x82,
    0xc2, 0xac, 0xc3, 0x83, 0xc6, 0x92, 0xc3, 0x82,
    0xc2, 0xa2, 0xc3, 0x83, 0xc2, 0xa2, 0xc3, 0xa2,
    0xe2, 0x82, 0xac, 0xc5, 0xa1, 0xc3, 0x82, 0xc2,
    0xac, 0xc3, 0x83, 0xe2, 0x80, 0x9a, 0xc3, 0x82, 0xc2, 0x9d
])  # 81 bytes - longer variant

count = 0
for pattern, name in [(corrupted_en_dash, 'en-dash'), (corrupted_em_dash, 'em-dash'), (corrupted_em_dash_long, 'em-dash-long')]:
    n = raw.count(pattern)
    if n:
        raw = raw.replace(pattern, b'-')
        count += n
        print(f'Replaced {n} occurrence(s) of {name} pattern')

with open(path, 'wb') as f:
    f.write(raw)

# Verify
with open(path, 'r', encoding='utf-8') as f:
    import json
    data = json.load(f)

print(f'\nVerification:')
for tool in data['tools']:
    if tool['id'] in ('chrome-session-viewer', 'browser-extensions-icons'):
        print(f'{tool["id"]}: {tool["summary"]}')
    
    # Check for any remaining non-printable corruption
    s = tool.get('summary', '')
    bad = [c for c in s if ord(c) < 32 and c not in '\n\r\t']
    if bad:
        print(f'WARNING: {tool["id"]} has control chars: {[hex(ord(c)) for c in bad]}')

print(f'\nTotal replacements: {count}')
print('Done')
